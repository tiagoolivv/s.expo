// Pure decisions behind the s-expo gate hook. Kept free of I/O so
// `node --test .claude/hooks/` can pin every rule without spawning an agent.
//
// Each rule exists because the action is either irreversible or bypasses a
// guardrail the project already relies on. The reason travels with the block,
// so the agent reads why and can pick the supported path instead.

const SHELL_RULES = [
  {
    test: command => /\bgit\s+push\b/.test(command)
      && /(?:\s|^)(?:--force(?:-with-lease)?|-f)\b/.test(command)
      && /\b(?:main|master)\b/.test(command),
    reason: 'Force-pushing main rewrites shared history. main only changes through a pull request (docs/conventions/git.md).',
  },
  {
    test: command => /\bgit\s+(?:commit|push|merge|rebase)\b/.test(command) && /--no-verify\b/.test(command),
    reason: 'Hooks are the local quality gate; --no-verify skips them. If a hook is wrong, fix the hook (docs/workflow.md §6).',
  },
  {
    test: command => /\brm\s+-[a-z]*(?:rf|fr)[a-z]*\s+(?:[/~*]|\$HOME|\.{1,2})\/?(?:\s|$)/i.test(command),
    reason: 'Recursive delete of the root, home or the whole project is never part of a task here.',
  },
  {
    test: command => /\beas\s+(?:build|submit)\b/.test(command) && /--profile[\s=]+production\b/.test(command),
    reason: 'Production builds and store submissions are a deliberate human decision (eas-build-prod.yml is manual on purpose).',
  },
  {
    test: command => /\beas\s+submit\b/.test(command),
    reason: 'Store submission is a deliberate human decision, never an agent step.',
  },
];

const PATH_RULES = [
  {
    test: path => /^(?:ios|android)\//.test(path),
    reason: 'ios/ and android/ are generated by expo prebuild. Change native config through a config plugin in app.config.ts.',
  },
  {
    test: path => /(?:^|\/)\.env(?:\.[\w-]+)*$/.test(path) && !path.endsWith('.example'),
    reason: 'Real env files hold secrets and are git-ignored. Edit the matching .env.*.example and run pnpm env:use.',
  },
  {
    test: path => path === 'pnpm-lock.yaml',
    reason: 'The lockfile is written by pnpm. Run pnpm add / pnpm remove / pnpm install instead of editing it.',
  },
  {
    test: path => path === 'uniwind-types.d.ts' || path === 'expo-env.d.ts',
    reason: 'Generated on every Metro run; hand edits are overwritten.',
  },
  {
    test: path => /^tools\/(?:crapper|dryer|mutator)\//.test(path),
    reason: 'tools/ is vendored upstream code (unclebob). Update it by re-copying the upstream commit, recorded in THIRD_PARTY_NOTICES.md.',
  },
];

/** Normalises an absolute or relative path to a repo-relative POSIX path. */
export function toRepoPath(filePath, projectDir) {
  const posix = String(filePath).replaceAll('\\', '/');
  const root = String(projectDir).replaceAll('\\', '/').replace(/\/$/, '');
  const relative = posix.startsWith(`${root}/`) ? posix.slice(root.length + 1) : posix;
  return relative.replace(/^\.\//, '');
}

function firstMatch(rules, value) {
  const rule = rules.find(candidate => candidate.test(value));
  return rule ? { allow: false, reason: rule.reason } : { allow: true };
}

/**
 * The command with heredoc bodies and quoted strings removed. A commit message
 * that mentions `--no-verify` is text, not a flag; matching on the raw string
 * blocked exactly that commit. What is left is what the shell will execute.
 */
export function executableText(command) {
  const lines = String(command ?? '').split('\n');
  const kept = [];
  let delimiter = null;
  for (const line of lines) {
    if (delimiter !== null) {
      if (line.trim() === delimiter)
        delimiter = null;
      continue;
    }
    kept.push(line);
    const heredoc = line.match(/<<-?\s*['"]?(\w+)['"]?/);
    if (heredoc)
      delimiter = heredoc[1];
  }
  return kept.join('\n').replace(/'[^']*'|"(?:[^"\\]|\\.)*"/g, '\'\'');
}

export function decideShell(command) {
  return firstMatch(SHELL_RULES, executableText(command));
}

export function decidePath(filePath, projectDir) {
  return firstMatch(PATH_RULES, toRepoPath(filePath ?? '', projectDir));
}

/** Decision for one PreToolUse event as Claude Code (and Codex) send it. */
export function decide(event, projectDir) {
  const input = event?.tool_input ?? {};
  if (event?.tool_name === 'Bash')
    return decideShell(input.command);
  if (input.file_path)
    return decidePath(input.file_path, projectDir);
  return { allow: true };
}

const LINTABLE = /\.(?:[cm]?[jt]sx?|json)$/;
const UNLINTED = /^(?:tools|docs|target|coverage|node_modules|ios|android|_workspace|\.metrics)\//;

/** Whether the feedback hook should run ESLint on an edited file. */
export function shouldLint(filePath, projectDir) {
  const path = toRepoPath(filePath ?? '', projectDir);
  return LINTABLE.test(path) && !UNLINTED.test(path) && !path.startsWith('/');
}
